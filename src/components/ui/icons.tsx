import React from 'react';

export interface IconProps extends React.SVGProps<SVGSVGElement> {
  size?: number | string;
  strokeWidth?: number | string;
  className?: string;
}

function createIcon(
  displayName: string,
  svgContent: (props: IconProps) => React.ReactNode
) {
  const Component = ({
    size = 24,
    strokeWidth = 2,
    className = '',
    ...props
  }: IconProps) => {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        aria-hidden="true"
        {...props}
      >
        {svgContent({ size, strokeWidth, className, ...props })}
      </svg>
    );
  };
  Component.displayName = displayName;
  return Component;
}

